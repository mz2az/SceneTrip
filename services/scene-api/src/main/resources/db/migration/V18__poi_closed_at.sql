-- 편의시설 폐업 표시 — 분기 갱신(`just seed-poi --update`)이 사라진 가게를 지우지 않고 표시만 한다.
--
-- 계획: docs/project/plans/poi-i18n-image.md §8.
--
-- ── 왜 지우지 않나 ─────────────────────────────────────────────────────────
--
-- 상가정보의 가게 번호는 이름 정정·행정구역 개편만으로도 바뀐다(6개월에 4 만 2 천 곳). 갱신은 그런 가게를
-- 좌표·이름으로 이어 주지만 휴리스틱이라 놓치는 것이 있다. 놓친 가게를 지우면 거기 붙은 번역·사진이 CASCADE
-- 로 사라지고 되돌릴 수 없다. 표시만 하면 행이 남아, 잘못 판정했을 때 표시를 지우면 된다.
--
-- 서버는 closed_at 이 있는 POI 를 지도·검색·상세 어디에도 내보내지 않는다(PoiStore). 같은 번호가 다음 판에
-- 다시 나오면 적재의 UPSERT 가 표시를 지운다.
--
-- 인덱스를 따로 두지 않는다. 조회는 위치(geom)·갈래 인덱스로 먼저 좁히고 이 칸은 남은 행에서 거른다 —
-- 폐업 행은 한 판에 수 % 라 거르는 비용이 작다.
ALTER TABLE poi ADD COLUMN closed_at TIMESTAMPTZ;

COMMENT ON COLUMN poi.closed_at IS
    '폐업으로 판정된 시각. NULL 이면 영업 중. 분기 갱신이 채우고, 같은 번호가 다시 나오면 적재가 지운다. 서버는 채워진 행을 내보내지 않는다';

-- 새 칸의 통계를 바로 잰다. 통계가 없으면 플래너가 `closed_at IS NULL` 을 기본값 0.5 % 로 추정해,
-- 거리순 목록이 GiST 의 가까운 순 스캔을 버리고 정렬로 돈다(2026-10-05 실측: 30 개 조회 비용
-- 1,416 → ANALYZE 뒤 14.96). ADD COLUMN 은 autovacuum 의 ANALYZE 를 부르지 않는다. 트랜잭션 안에서도 된다.
ANALYZE poi;
